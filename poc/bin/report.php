<?php declare(strict_types = 1);

/**
 * Builds the witnesses and the totals from the output of measure.php run
 * on both checkouts.
 *
 * Usage: php poc/bin/report.php <out-dir>
 *
 * For every pattern the phplrt side types against the engine, keeps one
 * witness, the first call refused, preferring preg_match() without flags,
 * and writes it with the PHPRegex type of the same call to
 * poc/witnesses/<set>.json and <set>.md. Prints the totals as a Markdown table.
 */

[$self, $outDir] = $argv + [null, null];
if ($outDir === null) {
	fwrite(STDERR, "usage: php poc/bin/report.php <out-dir>\n");
	exit(2);
}

const SETS = [
	'pcre2' => 'PCRE2 test suite (testdata/testinput*)',
	'php-src' => 'php-src ext/pcre tests',
];

const REASONS = [
	'falsy' => "a value that can be '0' or '' is typed non-falsy or non-empty",
	'value' => 'a value outside the type of its key',
	'absent' => 'a key the engine writes is typed absent',
	'present' => 'a key the engine leaves out is typed present',
	'subject' => 'the subject is narrowed further than the match proves',
];

const FLAGS = [PREG_OFFSET_CAPTURE => 'PREG_OFFSET_CAPTURE', PREG_UNMATCHED_AS_NULL => 'PREG_UNMATCHED_AS_NULL', PREG_SET_ORDER => 'PREG_SET_ORDER'];

/**
 * @return list<array<string, mixed>>
 */
function poc_lines(string $file): array
{
	if (!is_file($file)) {
		return [];
	}

	return array_map(static fn (string $line): array => json_decode($line, true), file($file, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: []);
}

function poc_call(string $label): string
{
	if ($label === 'subject') {
		return 'subject of preg_match()';
	}
	[$call, $flags] = explode(':', $label);
	$names = [];
	foreach (FLAGS as $flag => $name) {
		if ($flags !== 'null' && ((int) $flags & $flag) !== 0) {
			$names[] = $name;
		}
	}
	$function = $call === 'match' ? 'preg_match()' : ($call === 'all' ? 'preg_match_all()' : 'preg_match_all(), maybe matched');

	return $names === [] ? $function : $function . ', ' . implode(' | ', $names);
}

function poc_cell(string $text): string
{
	// bytes past UTF-8, as a class without u reads them, are written \xHH
	if (!mb_check_encoding($text, 'UTF-8')) {
		$text = (string) preg_replace_callback('/[\x80-\xff]/', static fn (array $byte): string => sprintf('\\x%02x', ord($byte[0])), $text);
	}

	return str_replace(['|', "\n"], ['\\|', '\\n'], $text);
}

function poc_value(string $serialized): string
{
	$value = unserialize(base64_decode($serialized));

	$json = json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);

	return is_string($value) || $json === false ? str_replace("\n", ' ', var_export($value, true)) : $json;
}

$totals = [];
foreach (SETS as $set => $label) {
	$types = [];
	foreach (poc_lines("$outDir/$set.phpregex.types.jsonl") as $row) {
		$types[$row['p'] . "\0" . $row['c']] = $row['t'];
	}
	$noShape = ['phplrt' => [], 'phpregex' => []];
	$patterns = [];
	foreach (['phplrt', 'phpregex'] as $side) {
		foreach (poc_lines("$outDir/$set.$side.types.jsonl") as $row) {
			$patterns[$row['p']] = true;
			if ($row['c'] === 'match:null' && $row['t'] === null) {
				$noShape[$side][$row['p']] = true;
			}
		}
	}

	$witnesses = [];
	foreach (poc_lines("$outDir/$set.phplrt.refusals.jsonl") as $row) {
		$known = $witnesses[$row['p']] ?? null;
		if ($known !== null && ($known['call'] === 'match:null' || $row['c'] !== 'match:null')) {
			continue;
		}
		$witnesses[$row['p']] = [
			'pattern' => $row['p'],
			'call' => $row['c'],
			'subject' => $row['s'],
			'engine' => $row['e'],
			'reason' => $row['reason'],
			'key' => $row['key'],
			'phplrt' => $row['t'],
			'phpregex' => $types[$row['p'] . "\0" . $row['c']] ?? null,
		];
	}
	$witnesses = array_values($witnesses);
	$refusedOnPhpregex = [];
	foreach (poc_lines("$outDir/$set.phpregex.refusals.jsonl") as $row) {
		$refusedOnPhpregex[$row['p']] = true;
	}

	file_put_contents(__DIR__ . "/../witnesses/$set.json", json_encode($witnesses, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE) . "\n");

	$reasons = array_count_values(array_column($witnesses, 'reason'));
	$md = "# $label\n\nOne witness for each of the " . count($witnesses) . " patterns whose inferred type the engine contradicts with the parser generated by phplrt. `php poc/bin/verify.php` replays them.\n\n";
	foreach (REASONS as $reason => $text) {
		$md .= '- ' . $text . ': ' . ($reasons[$reason] ?? 0) . "\n";
	}
	$md .= "\n| pattern | call | subject | the engine writes | phplrt | PHPRegex | why |\n|---|---|---|---|---|---|---|\n";
	foreach ($witnesses as $w) {
		$md .= sprintf(
			"| `%s` | %s | `%s` | `%s` | `%s` | `%s` | %s |\n",
			poc_cell($w['pattern']),
			poc_call($w['call']),
			poc_cell(var_export(base64_decode($w['subject']), true)),
			poc_cell(poc_value($w['engine'])),
			poc_cell((string) $w['phplrt']),
			poc_cell($w['phpregex'] ?? 'no shape'),
			($w['key'] === null ? '' : 'key `' . $w['key'] . '`: ') . REASONS[$w['reason']],
		);
	}
	$md .= "\n## Patterns the parser generated by phplrt infers no shape for\n\n" . count($noShape['phplrt']) . " patterns, `preg_match()` without flags.\n\n| pattern | PHPRegex |\n|---|---|\n";
	foreach (array_keys($noShape['phplrt']) as $pattern) {
		$md .= sprintf("| `%s` | `%s` |\n", poc_cell($pattern), poc_cell($types[$pattern . "\0match:null"] ?? 'no shape'));
	}
	file_put_contents(__DIR__ . "/../witnesses/$set.md", $md);

	$totals[$set] = [
		'patterns' => count($patterns),
		'phplrt' => count($witnesses),
		'phpregex' => count($refusedOnPhpregex),
		'phplrtNoShape' => count($noShape['phplrt']),
		'phpregexNoShape' => count($noShape['phpregex']),
	];
}

$table = "| | phplrt | PHPRegex |\n|---|---|---|\n";
foreach ($totals as $set => $t) {
	$table .= sprintf("| %s (%s patterns): types the engine contradicts | %d | %d |\n", SETS[$set], number_format($t['patterns']), $t['phplrt'], $t['phpregex']);
}
foreach ($totals as $set => $t) {
	$table .= sprintf("| %s: patterns with no `preg_match()` shape | %d | %d |\n", SETS[$set], $t['phplrtNoShape'], $t['phpregexNoShape']);
}

// Each contradicted pattern once, under the first family it matches, in this order.
$families = [
	['a `(?#...)` comment is read as pattern syntax', static fn (array $w, string $p, string $m): bool => str_contains($p, '(?#')],
	['a lone `\\E` is read as a quantifiable atom', static fn (array $w, string $p, string $m): bool => preg_match('/\\\\E/', $p) === 1 && !str_contains($p, '\\Q')],
	['`\\Q...\\E` is read as pattern syntax', static fn (array $w, string $p, string $m): bool => str_contains($p, '\\Q')],
	['a `MARK` name under `/x` loses the `#comment` the engine keeps in it', static fn (array $w, string $p, string $m): bool => $w['key'] === 'MARK'],
	['a class without `/u` is read as characters where the engine reads bytes', static fn (array $w, string $p, string $m): bool => preg_match('/[\x80-\xff]/', $p) === 1 && !str_contains($m, 'u') && $w['reason'] === 'value'],
	['`(?n)` and `/n`: groups that do not capture are typed as captured', static fn (array $w, string $p, string $m): bool => str_contains($p, '(?n') || str_contains($m, 'n')],
	['an inline `(?x)` is not read: skipped whitespace is typed as text', static fn (array $w, string $p, string $m): bool => str_contains($p, '(?x)')],
	['an inline `(?i)`, `(?i:...)` or `(?^i)` is not read: a caseless match is typed by its spelling', static fn (array $w, string $p, string $m): bool => preg_match('/\(\?\^?i[):]/', $p) === 1 && $w['reason'] === 'value'],
	['`\\d` and `[[:digit:]]` under `/u` or `(*UCP)` read Unicode digits, which are not numeric strings', static fn (array $w, string $p, string $m): bool => $w['reason'] === 'value' && preg_match('/\\\\d|\[:digit:\]|\\\\p\{?N/', $p) === 1],
	["a value that can be `'0'` or `''` is typed `non-falsy-string` or `non-empty-string`: `\\w`, `\\S`, `.`, `\\p{N}`, `\\X`, `[[:alnum:]]`, negated classes, lookbehinds", static fn (array $w, string $p, string $m): bool => $w['reason'] === 'falsy'],
];
$examples = ['/\pN/', '/(\d)/u', '/(?i)(a)/', '/(?x)( a )/', '/\Q(a)\E/', '/(?n)(a)(?<x>b)/'];
$all = [];
foreach (array_keys(SETS) as $set) {
	foreach (json_decode((string) file_get_contents(__DIR__ . "/../witnesses/$set.json"), true) as $w) {
		$all[] = $w;
	}
}
$used = [];
$familyTable = "| what the generated parser reads differently | patterns | witness | the engine writes | phplrt | PHPRegex |\n|---|---|---|---|---|---|\n";
foreach ($families as [$label, $test]) {
	$members = [];
	foreach ($all as $i => $w) {
		$modifiers = preg_match('/[a-zA-Z]*$/', $w['pattern'], $tail) === 1 ? $tail[0] : '';
		if (!isset($used[$i]) && $test($w, $w['pattern'], $modifiers)) {
			$members[] = $w;
			$used[$i] = true;
		}
	}
	if ($members === []) {
		continue;
	}
	$example = $members[0];
	foreach ($members as $w) {
		if (in_array($w['pattern'], $examples, true)) {
			$example = $w;
			break;
		}
	}
	$familyTable .= sprintf(
		"| %s | %d | `%s` on `%s` | `%s` | `%s` | `%s` |\n",
		ucfirst($label),
		count($members),
		poc_cell($example['pattern']),
		poc_cell(var_export(base64_decode($example['subject']), true)),
		poc_cell(poc_value($example['engine'])),
		poc_cell((string) $example['phplrt']),
		poc_cell($example['phpregex'] ?? 'no shape'),
	);
}

$readme = (string) file_get_contents(__DIR__ . '/../README.template.md');
file_put_contents(__DIR__ . '/../README.md', strtr($readme, ['{totals}' => rtrim($table), '{families}' => rtrim($familyTable)]));
echo $table, "\n", $familyTable;
